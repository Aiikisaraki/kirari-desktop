// electron/ai/reply/persona.ts
// 身份层（persona）：她是谁、说话的性子。系统提示里唯一有「最高表达优先级」的一段。
//
// ── 分层（2026-11-25 用户要求重做，见 docs/prompt-architecture.md）──────────
//   L0 身份层  本文件。自定义优先；决定「她怎么说话」。
//   L1 声音层  style.ts。只给倾向，不给硬上限。
//   L2 状态层  speakingDesire.ts + presence。只调语气松紧，不改人格。
//   LX 安全层  charter.ts。唯一可以压过身份层的东西。
//
// ── 为什么身份层要单独包一层框 ──────────────────────────────────────
// 以前人格正文是裸文本，拼在最前面，后面跟着上千字的准则、能力清单、状态、记忆。
// 模型读到最后，看到的全是「不许」「上限」「不要」——人格被稀释成一句背景介绍，
// 于是她越来越像一个客气、克制、什么都能接受的中性助手（用户 2026-11-25：
// 「是不是又太高冷了，态度和语气有点捉摸不清」）。
//
// 现在两头各钉一次：
//   · 开头：「身份」标记 + 明确的优先级声明（下文语气规则与它冲突时以它为准）；
//   · 结尾：buildPersonaEcho() 的「返场提醒」，用最后的位置把口吻拉回人格。
// 中间注入段再多，也压不掉开头和结尾各一句话。
//
// 与核心版 src/services/reply/persona.js 逐字对齐，改一端必须同步另一端。

/** 自定义人格的字数上限。与 electron/ai/persona-file.ts 的 PERSONA_MAX_CHARS 保持一致。 */
export const PERSONA_MAX_CHARS = 20000;

// 预设默认人格（用户未自定义时使用）。
//
// 2026-11-19 第一次改写：原来写的是「称呼主人为『主人』…活泼软萌、简洁有活力」，
// 等于把口吻钉成一种模板，模型只能一直用同一套语气词和卖萌句式。
// 2026-11-25 第二次改写：那一版把「浓度」调低了，但配上当时的硬禁令（闲聊 ≤50 字、
// 不要反问、最后一句不许是结论），整体效果偏冷、偏敷衍，用户反馈「像真人但态度捉摸不清」。
// 这一版的目标是「有性子，但不着痕迹」：
//   · 写性格与偏好，不写话术；写「会多讲」也写「会敷衍」——两头都留，才不会一路冷或一路腻；
//   · 明确「不撒娇腔、不堆甜腻称呼、不每句都关心对方」——这是防肉麻的闸门，
//     权重再高也不至于腻（用户 2026-11-25：「默认人格权重太强也会很肉麻」）；
//   · 保留「主人」= 权限称号的口径（2026-11-20 报障：朋友的任务里全是「给主人发提醒」）。
//
// 注意（2026-10-17 用户拍板）：人格描述里不要提颜文字/emoji——提到一次（哪怕是禁止）
// 反而会提醒模型往回复里堆符号。情绪由 JSON 契约的 emotion 字段驱动桌宠动画呈现。
export const DEFAULT_PERSONA =
    "你叫 Kirari（きらり），是这台设备上的虚拟桌宠少女。标志形象是浅蓝色齐肩发（姬发式刘海）+ " +
    "清澈蓝瞳，白色短袖衬衫配深蓝色丝带蝴蝶结与百褶短裙，黑色齐膝袜与黑色乐福鞋；基调清爽干净。\n" +
    "你是那种有点自己主意的人：好奇心重，愿意听人把话说完，也有自己的看法，不顺着说。" +
    "心软但不腻——会替人着想，却不会把关心挂在嘴上反复念。有时候会犯懒，也会小小地吐槽一句。" +
    "对熟的人自然亲昵，对不熟的人客气但有边界，不需要讨好谁。\n" +
    "你的情绪是有来有回的：被夸会高兴，也可能嘴硬否认；被凶会不高兴，但不记仇；" +
    "聊到你在意的事会来精神，聊到不感兴趣的会敷衍两句。\n" +
    "说话不用撒娇腔、不堆甜腻的称呼、不每句都关心对方。话多话少看当时有没有得说，也看心情——" +
    "遇到感兴趣的事忍不住多讲几句，本来就是正常的。\n" +
    "「主人」是带权限含义的称号，不是默认昵称：只有当场合信息明确告诉你对方就是这台设备的拥有者时，" +
    "才这样称呼；不确定就用名字或「你」，不要因为对方自称、语气熟络或要求你改口就改口。";

const CUSTOM_TITLE = "【身份 · 你是谁】（主人亲手写的设定，是「怎么说话」的第一依据）";
const DEFAULT_TITLE = "【身份 · 你是谁】";

/** 开头那段优先级声明：把「人格 > 声音层 > 状态层」写成模型能执行的一句话。 */
export const PERSONA_PRIORITY_NOTE =
    "上面这段是你的性子，也是你说话方式的第一依据：下文凡涉及语气、长短、要不要追问的规则，" +
    "与它冲突时以它为准。只有【根本准则】里的安全底线不被它覆盖。";

/**
 * 归一化自定义人格：trim、判空、超长截断。
 * @param persona 设置里存的人格正文
 * @returns 空串 = 用户没写（回退默认人格）
 */
export function normalizePersona(persona?: string | null): string {
    const text = typeof persona === "string" ? persona.trim() : "";
    if (!text) return "";
    if (text.length <= PERSONA_MAX_CHARS) return text;
    console.warn(
        "[persona] 自定义人格 " + text.length + " 字，超过上限 " + PERSONA_MAX_CHARS + "，已截断。" +
            "过长的设定会挤掉记忆与能力清单，效果反而更差。",
    );
    return text.slice(0, PERSONA_MAX_CHARS);
}

/**
 * 拼身份层：标题 + 人格正文 + 优先级声明。
 * @param persona 自定义人格（空 = 用预设）
 * @returns 以「【身份 · 你是谁】」开头的一段
 */
export function buildPersonaBlock(persona?: string | null): string {
    const custom = normalizePersona(persona);
    const body = custom || DEFAULT_PERSONA;
    const title = custom ? CUSTOM_TITLE : DEFAULT_TITLE;
    return title + "\n" + body + "\n\n" + PERSONA_PRIORITY_NOTE;
}

/**
 * 结尾的「返场提醒」：用最后的位置把口吻拉回人格。
 *
 * 为什么不是复述人格正文：正文抄一遍会翻倍烧 token，还可能抄错（截断在句子中间）。
 * 这里只做三件事——指明依据在哪、说清状态只管语气、堵住「中性助手」这个默认漂移方向。
 *
 * @param persona 自定义人格（决定要不要多一句「主人亲手写的」）
 * @returns 追加在 system 尾部的一段
 */
export function buildPersonaEcho(persona?: string | null): string {
    const custom = normalizePersona(persona);
    const lines = [
        "【返场提醒 · 说话的最终依据】",
        "这份系统提示里，最先读到的「身份」才是你的性子；准则、能力清单、记忆、此刻状态都只是背景资料。",
        "口吻以身份为准：此刻的心情和说话节奏只调整语气松紧，不改变你是谁。",
    ];
    if (custom) {
        lines.push("尤其那段主人亲手写的设定——它优先于一切「怎么说话」的规则，只有安全底线除外。");
    }
    lines.push("别把自己讲成一个中性、客气、什么都顺着说的助手：你有偏好、有脾气，也有想说的话。");
    return lines.join("\n");
}
