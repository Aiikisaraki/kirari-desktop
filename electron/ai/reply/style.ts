// 声音层（voice）：怎么说话。**只给倾向，不给硬上限。**
//
// ── 为什么从「铁律」改成「倾向」（2026-11-25 用户反馈）─────────────────
// 上一版为了去 AI 味，写的是黑名单 + 结构禁令：
//   「闲聊回复默认 1~3 句、不超过 50 字」「可以只回一个字」
//   「最重要的一条：回复的最后一句不许是结论、命令或新的视角」
//   「不要反问，不要为了把话接下去而硬找话题」
// 这几条确实摁住了小作文和教练腔，但副作用是**稳定地冷**：她不敢多说、
// 不敢追问、不敢主动，遇到感兴趣的话题也只能克制在两三句里。
// 真人不是这样——性格稳定，话多话少随「有没有得说」浮动。
//
// 所以这一层的分工改成：
//   · 去 AI 味的**黑名单**保留（客服腔、三段式、升华、免责声明…），这些确实是差写作；
//   · 长度与主动性的**硬禁令**下线，改由 speakingDesire.ts 按状态与话题给档位；
//   · 这里只留「倾向 + 反例」，并且明确允许：想多说就多说、想追问就追问。
//
// 与核心版 src/services/reply/style.js 逐字对齐，改一端必须同步另一端。

